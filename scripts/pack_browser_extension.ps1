<#
.SYNOPSIS
  Packs browser-extension\ into a signed CRX3 for Chromium enterprise force-install and writes
  the update manifest consumed by ExtensionInstallForcelist.

.DESCRIPTION
  Uses the installed Microsoft Edge (always present on Windows 10/11) or Google Chrome
  `--pack-extension` to produce the CRX. The signing key lives in certs\ (git-ignored) and is
  generated by the browser on first pack. The `key` field is stripped from the staged manifest
  so the CRX ID derives from the signing key.

  Outputs (dist\browser-extension\):
    oshoosi-browser-sensor.crx, update.xml, extension_id.txt
  and appends the packed ID to config\browser_sensor_origins.txt so the daemon accepts pairing
  from the force-installed build.
#>
[CmdletBinding()]
param(
    [string]$KeyPath = '',
    [string]$CodebaseUrl = 'http://127.0.0.1:3030/browser-sensor/oshoosi-browser-sensor.crx'
)

$ErrorActionPreference = 'Stop'
$repo = Resolve-Path (Join-Path $PSScriptRoot '..')
$src = Join-Path $repo 'browser-extension'
$out = Join-Path $repo 'dist\browser-extension'
$stage = Join-Path $env:TEMP ("oshoosi-sensor-stage-" + [guid]::NewGuid().ToString('N'))
if (-not $KeyPath) { $KeyPath = Join-Path $repo 'certs\oshoosi_browser_sensor.pem' }

$browser = @(
    "${env:ProgramFiles(x86)}\Microsoft\Edge\Application\msedge.exe",
    "$env:ProgramFiles\Microsoft\Edge\Application\msedge.exe",
    "$env:ProgramFiles\Google\Chrome\Application\chrome.exe",
    "${env:ProgramFiles(x86)}\Google\Chrome\Application\chrome.exe"
) | Where-Object { $_ -and (Test-Path -LiteralPath $_) } | Select-Object -First 1
if (-not $browser) { throw 'Microsoft Edge or Google Chrome is required to pack the extension' }

New-Item -ItemType Directory -Force -Path $stage, $out, (Split-Path $KeyPath) | Out-Null
$include = @('manifest.json', 'background.js', 'lib', 'options')
foreach ($item in $include) { Copy-Item -Recurse -Force -LiteralPath (Join-Path $src $item) -Destination $stage }
$manifestPath = Join-Path $stage 'manifest.json'
$manifest = Get-Content -LiteralPath $manifestPath -Raw | ConvertFrom-Json
$manifest.PSObject.Properties.Remove('key')
$manifest | Add-Member -NotePropertyName 'update_url' -NotePropertyValue ($CodebaseUrl -replace 'oshoosi-browser-sensor\.crx$', 'update.xml') -Force
$manifest | ConvertTo-Json -Depth 10 | Set-Content -LiteralPath $manifestPath -Encoding utf8

$args = @("--pack-extension=$stage", '--no-message-box')
if (Test-Path -LiteralPath $KeyPath) { $args += "--pack-extension-key=$KeyPath" }
$p = Start-Process -FilePath $browser -ArgumentList $args -Wait -PassThru -WindowStyle Hidden
$crx = "$stage.crx"
$pem = "$stage.pem"
if (-not (Test-Path -LiteralPath $crx)) { throw "Packing failed (exit $($p.ExitCode))" }
if ((Test-Path -LiteralPath $pem) -and -not (Test-Path -LiteralPath $KeyPath)) { Move-Item -LiteralPath $pem -Destination $KeyPath }

# Extension ID = first 128 bits of SHA-256(SubjectPublicKeyInfo DER), alphabet a-p.
$pemLines = (Get-Content -LiteralPath $KeyPath) | Where-Object { $_ -and (-not $_.StartsWith('-----')) }
$derBytes = [Convert]::FromBase64String(($pemLines -join ''))
# PKCS#8 PrivateKeyInfo or PKCS#1 RSAPrivateKey -> extract public key SPKI via Python cryptography or fallback SHA-256 of DER
$id = (& python -c "
import hashlib, sys
from cryptography.hazmat.primitives import serialization
with open(sys.argv[1], 'rb') as f:
    priv = serialization.load_pem_private_key(f.read(), password=None)
spki = priv.public_key().public_bytes(
    serialization.Encoding.DER,
    serialization.PublicFormat.SubjectPublicKeyInfo
)
digest = hashlib.sha256(spki).digest()[:16]
print(''.join(chr(97 + (b >> 4)) + chr(97 + (b & 15)) for b in digest))
" $KeyPath 2>$null)
if (-not $id) {
    $sha256 = [System.Security.Cryptography.SHA256]::Create()
    $hash = $sha256.ComputeHash($derBytes)
    $id = -join ($hash[0..15] | ForEach-Object { [char](97 + ($_ -shr 4)); [char](97 + ($_ -band 15)) })
}
$id = $id.Trim()

Copy-Item -Force -LiteralPath $crx -Destination (Join-Path $out 'oshoosi-browser-sensor.crx')
Set-Content -LiteralPath (Join-Path $out 'extension_id.txt') -Value $id -Encoding ascii
$version = $manifest.version
@"
<?xml version='1.0' encoding='UTF-8'?>
<gupdate xmlns='http://www.google.com/update2/response' protocol='2.0'>
  <app appid='$id'>
    <updatecheck codebase='$CodebaseUrl' version='$version' />
  </app>
</gupdate>
"@ | Set-Content -LiteralPath (Join-Path $out 'update.xml') -Encoding utf8

$origins = Join-Path $repo 'config\browser_sensor_origins.txt'
if (-not (Test-Path -LiteralPath $origins) -or -not (Select-String -LiteralPath $origins -SimpleMatch $id -Quiet)) {
    Add-Content -LiteralPath $origins -Value $id
}
Remove-Item -Recurse -Force -LiteralPath $stage, $crx -ErrorAction SilentlyContinue
Write-Output "Packed OshoosiClaw Browser DLP Sensor $version (ID $id) -> $out"
